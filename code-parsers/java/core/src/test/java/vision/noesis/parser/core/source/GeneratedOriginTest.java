package vision.noesis.parser.core.source;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import vision.noesis.parser.core.ArtifactInput;
import vision.noesis.parser.core.EngineKind;
import vision.noesis.parser.core.JavaParser;
import vision.noesis.parser.core.ParseRequest;
import vision.noesis.parser.core.ParseSession;
import vision.noesis.parser.model.CodeModelFile;
import vision.noesis.parser.model.DeclarationNode;
import vision.noesis.parser.model.Origin;

/**
 * A source under the build directory was generated by the build. Gradle's classes are not a child of its build directory
 * ({@code build/classes/java/main}) as Maven's are ({@code target/classes}), so the plugins pass the build directory.
 */
class GeneratedOriginTest {

    @TempDir
    Path root;

    @Test
    void anAnnotationProcessorsSourceInGradlesBuildDirectoryIsGenerated() throws IOException {
        Path generated = root.resolve("build/generated/sources/annotationProcessor/java/main");
        CodeModelFile model = parse(generated, root.resolve("build/classes/java/main"), root.resolve("build"));

        assertEquals(Origin.DECLARED, originOf(model, "T:p.Declared"));
        assertEquals(Origin.GENERATED, originOf(model, "T:p.Generated"));
    }

    @Test
    void withoutABuildDirectoryTheOutputDirectorysParentIsOneAsInMavensLayout() throws IOException {
        Path generated = root.resolve("target/generated-sources/annotations");
        CodeModelFile model = parse(generated, root.resolve("target/classes"), null);

        assertEquals(Origin.DECLARED, originOf(model, "T:p.Declared"));
        assertEquals(Origin.GENERATED, originOf(model, "T:p.Generated"));
    }

    @Test
    void anOutputDirectoryRightInTheModuleDoesNotMakeItsSourcesGenerated() throws IOException {
        Path generated = root.resolve("target/generated-sources/annotations");
        CodeModelFile model = parse(generated, root.resolve("classes"), null);

        assertEquals(Origin.DECLARED, originOf(model, "T:p.Declared"));
    }

    private CodeModelFile parse(Path generated, Path classes, Path buildDirectory) throws IOException {
        Path sources = root.resolve("src/main/java");
        write(sources.resolve("p/Declared.java"), "package p; public class Declared { Generated g; }");
        write(generated.resolve("p/Generated.java"), "package p; public class Generated {}");
        ArtifactInput input = new ArtifactInput("p", "origin", "1", root, null, List.of(sources, generated), classes, List.of(), 17,
                StandardCharsets.UTF_8, "jar", null, "origin", buildDirectory);
        ParseRequest request = new ParseRequest(root, "origin", "", "", root.resolve("out"), EngineKind.SOURCE, List.of(input));
        return JavaParser.engineFor(EngineKind.SOURCE).parse(input, new ParseSession(new JavaParser("0.0.0").generator(), request));
    }

    private static void write(Path file, String content) throws IOException {
        Files.createDirectories(file.getParent());
        Files.writeString(file, content, StandardCharsets.UTF_8);
    }

    private static Origin originOf(CodeModelFile model, String id) {
        return model.nodes().stream().filter(node -> node.id().value().equals(id)).findFirst()
                .map(DeclarationNode::origin).orElseThrow(() -> new AssertionError(id + " not in " + model.nodes()));
    }
}
