package vision.noesis.parser.core;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.function.Function;
import org.junit.jupiter.api.Test;

/**
 * The committed comparison of the three engines over both fixtures: every unfiltered difference from the source engine
 * counted by category, beside what each engine holds. The diff on a change is the review of what an engine gained or
 * lost; {@code NOESIS_UPDATE_GOLDEN=1 mvn test} rewrites it. The parse times are printed, not committed.
 */
class EngineComparisonReportTest {

    static final Path GOLDEN = GoldenModelTest.GOLDEN.resolve("engine-comparison.md");

    @Test
    void comparisonReportMatchesGolden() throws IOException {
        StringBuilder report = new StringBuilder();
        report.append("# Source engine versus bytecode engine versus hybrid engine over the Java fixtures\n\n");
        report.append("Regenerated by `NOESIS_UPDATE_GOLDEN=1 mvn -B -pl core -am test`; a row that changes is a change in what one engine sees. ");
        report.append("The source engine is the baseline of every difference table. The syntax fixture is compiled without annotation processors; the Lombok fixture's members exist only in its class files.\n");
        report.append(EngineComparisonReport.of(engines(Fixtures::parse)));
        report.append(EngineComparisonReport.of(engines(Fixtures::lombok)));
        StringBuilder times = new StringBuilder("Engine parse times: syntax fixture");
        for (EngineKind engine : EngineKind.values()) times.append(' ').append(engine.id()).append(' ').append(Fixtures.parseMillis(engine)).append(" ms,");
        times.append(" Lombok fixture");
        for (EngineKind engine : EngineKind.values()) times.append(' ').append(engine.id()).append(' ').append(Fixtures.lombokMillis(engine)).append(" ms,");
        System.out.println(times.substring(0, times.length() - 1));
        if ("1".equals(System.getenv("NOESIS_UPDATE_GOLDEN"))) {
            Files.createDirectories(GOLDEN.getParent());
            Files.writeString(GOLDEN, report.toString(), StandardCharsets.UTF_8);
            return;
        }
        String expected = Files.exists(GOLDEN) ? Files.readString(GOLDEN, StandardCharsets.UTF_8) : "";
        assertEquals(expected, report.toString(), "engine-comparison.md differs; run NOESIS_UPDATE_GOLDEN=1 mvn test after an intended engine change.");
    }

    private static List<EngineComparisonReport.Labelled> engines(Function<EngineKind, ParseResult> parse) {
        List<EngineComparisonReport.Labelled> engines = new ArrayList<>();
        for (EngineKind engine : EngineKind.values()) engines.add(new EngineComparisonReport.Labelled(engine.id(), parse.apply(engine)));
        return engines;
    }
}
